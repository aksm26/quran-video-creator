class Row(NamedTuple):
    language: str  # English name of the language
    key: str  # the label used in settings and on the command line
    id: int  # Quran.com translation id
    code: str
    translator: str


def translator(api_name: str) -> str:
    """The API's name for a translation, without a leading "<Language> Translation - " that would repeat the
    language in the app's list. A variant in brackets is kept after the name."""
    name = api_name.strip()
    match = re.fullmatch(r"[^()]*? Translation(?: \((.+?)\))? - (.+)", name)
    if not match:
        return name
    variant, who = match.groups()
    return f"{who} ({variant})" if variant else who


assert translator("Swahili Translation - Ali Muhsin Al-Barwani") == "Ali Muhsin Al-Barwani"
assert translator(" Kirundi Translation - Yusuf Gheti") == "Yusuf Gheti"
assert translator("Chinese Translation (Simplified) - Ma Jian") == "Ma Jian (Simplified)"
assert translator("Turkish Translation (Diyanet)") == "Turkish Translation (Diyanet)"  # no translator named
assert translator("Tafheem e Qur'an - Syed Abul A'la Maududi") == "Tafheem e Qur'an - Syed Abul A'la Maududi"


def lookup(names: dict, code: str) -> str | None:
    return names.get(code) or names.get(code.replace("_", "-"))  # some CLDR tables write fa_AF as fa-AF


def translation_rows(english: dict) -> list[Row]:
    """Every translation, in the order the app lists them: English first (the default, Saheeh International,
    at the top), then by language and name."""
    api_rows = QuranClient()._json("v4/resources/translations")["translations"]
    unknown = sorted({t["language_name"].strip().lower() for t in api_rows} - set(API_LANGUAGE_CODES))
    if unknown:
        sys.exit("New languages in the API: add them to API_LANGUAGE_CODES first: " + ", ".join(map(repr, unknown)))
    rows, seen = [], set()
    for t in api_rows:
        if "transliteration" in (t["name"] + str(t.get("slug"))).lower():
            continue  # a transliteration is not a translation
        api_name = t["language_name"].strip().lower()
        code = API_LANGUAGE_CODES[api_name]
        language = lookup(english, code) or api_name.split(",")[0].strip().title()
        key = f'{language} ({translator(t["name"])})'
        if key in seen:
            key = f'{key} #{t["id"]}'
        seen.add(key)
        rows.append(Row(language, key, t["id"], code, translator(t["name"])))
    rows.sort(key=lambda r: (r.code != "en", r.language, r.key != "English (Saheeh International)", r.key))
    return rows


def language_names(rows: list[Row], english: dict) -> dict[str, dict[str, str]]:
    """{app language: {language code: name}} for every language a translation or the app uses."""
    codes = sorted({r.code for r in rows} | set(LANGUAGES))
    names = {}
    for ui in LANGUAGES:
        local = Locale(ui).languages
        table = {}
        for code in codes:
            name = (lookup(local, code) or lookup(english, code)
                    or next((r.language for r in rows if r.code == code), code))
            table[code] = name[0].upper() + name[1:]
        names[ui] = table
    return names


def write_translations(rows: list[Row]) -> None:
    head = f'''"""Every Quran translation Quran.com offers (generated from /v4/resources/translations, October 2026).
{GENERATED}

The key is a stable English label used in settings and on the command line; the app shows the language in the
user's own language instead (see language_names.py)."""

from dataclasses import dataclass


@dataclass(frozen=True)
class Translation:
    key: str
    id: int
    lang: str  # language code
    translator: str


LIST: tuple[Translation, ...] = (
'''
    entries = "\n".join(f"    Translation({r.key!r}, {r.id}, {r.code!r}, {r.translator!r})," for r in rows)
    tail = '''
)

TRANSLATIONS: dict[str, int | None] = {"None": None, **{t.key: t.id for t in LIST}}
BY_KEY: dict[str, Translation] = {t.key: t for t in LIST}
DEFAULT_TRANSLATION = LIST[0].key  # English, Saheeh International


def key_for_id(translation_id: int | None) -> str:
    """The key of the translation with this Quran.com id ("None" for no translation)."""
    return next((t.key for t in LIST if t.id == translation_id), "None")
'''
    (OUT / "translations.py").write_text(head + entries + tail, encoding="utf8")


def write_language_names(names: dict[str, dict[str, str]]) -> None:
    lines = ['"""Language names in each app language, from the Unicode CLDR (generated once; no runtime dependency).',
             GENERATED,
             "",
             'NAMES[app language][language code] is how that language is called in the app language, '
             'e.g. Spanish in Portuguese is "Espanhol"."""',
             "",
             "NAMES: dict[str, dict[str, str]] = {"]
    for ui, table in names.items():
        lines.append(f"    {ui!r}: {{")
        lines += [f"        {code!r}: {name!r}," for code, name in table.items()]
        lines.append("    },")
    lines += ["}", "", "", "def language_name(code: str, ui: str) -> str:",
              '    return NAMES.get(ui, NAMES["en"]).get(code) or NAMES["en"].get(code, code)', ""]
    (OUT / "language_names.py").write_text("\n".join(lines), encoding="utf8")


def main() -> None:
    english = Locale("en").languages
    rows = translation_rows(english)
    names = language_names(rows, english)
    write_translations(rows)
    write_language_names(names)
    print(len(rows), "translations;", len({r.code for r in rows} | set(LANGUAGES)), "language codes;",
          len(LANGUAGES), "app languages")
    print(names["pt"]["es"], names["pt"]["pt"], names["ja"]["en"], names["en"]["fa_AF"], names["ar"]["mrw"])


if __name__ == "__main__":
    main()
